//! Embedded bitmap typography engine for software surfaces.

use crate::draw::Surface;
use crate::geom::{Color, Rect};

pub struct Font {
    pub char_width: i32,
    pub char_height: i32,
}

impl Font {
    pub const fn regular() -> Self {
        Self {
            char_width: 8,
            char_height: 14,
        }
    }

    pub const fn small() -> Self {
        Self {
            char_width: 6,
            char_height: 10,
        }
    }

    pub const fn bold() -> Self {
        Self {
            char_width: 8,
            char_height: 14,
        }
    }

    pub fn measure_str(&self, text: &str) -> Rect {
        let w = (text.chars().count() as i32) * self.char_width;
        Rect::new(0, 0, w, self.char_height)
    }
}

pub fn draw_text_font<S: Surface + ?Sized>(
    s: &mut S,
    x: i32,
    y: i32,
    text: &str,
    color: Color,
    font: &Font,
) {
    let mut cx = x;
    for ch in text.chars() {
        if ch == '\n' {
            continue;
        }
        draw_char(s, cx, y, ch, color, font);
        cx += font.char_width;
    }
}

fn draw_char<S: Surface + ?Sized>(s: &mut S, x: i32, y: i32, ch: char, color: Color, font: &Font) {
    if !ch.is_ascii() || ch == ' ' {
        return;
    }

    let glyph = get_glyph_bitmap(ch);
    for row in 0..8 {
        let bits = glyph[row];
        for col in 0..8 {
            if (bits & (1 << (7 - col))) != 0 {
                let px = x + ((col as i32) * font.char_width) / 8;
                let py = y + ((row as i32) * font.char_height) / 8;
                s.put_pixel(px, py, color);
                if font.char_width >= 8 && font.char_height >= 14 {
                    s.put_pixel(px + 1, py, color);
                }
            }
        }
    }
}

